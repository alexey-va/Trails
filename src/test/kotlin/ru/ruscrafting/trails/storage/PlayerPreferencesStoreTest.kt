package ru.ruscrafting.trails.storage

import io.kotest.core.spec.style.FreeSpec
import io.kotest.matchers.shouldBe
import io.mockk.every
import io.mockk.mockkConstructor
import io.mockk.unmockkConstructor
import ru.ruscrafting.trails.config.YamlConfig
import java.nio.file.Files
import java.nio.file.Path
import java.util.UUID
import java.util.concurrent.CountDownLatch
import java.util.concurrent.TimeUnit
import java.util.concurrent.atomic.AtomicInteger

class PlayerPreferencesStoreTest :
    FreeSpec({
        "loads and preserves the legacy players.yml shape" {
            val folder = Files.createTempDirectory("trails-players-")
            val first = UUID.fromString("11111111-1111-1111-1111-111111111111")
            val second = UUID.fromString("22222222-2222-2222-2222-222222222222")
            try {
                Files.writeString(
                    folder.resolve("players.yml"),
                    """
                    players:
                      $first:
                        enable: false
                      $second:
                        boost: true
                    """.trimIndent(),
                )

                withPreferences(folder) { store ->
                    store.get(first).trailsEnabled(default = true) shouldBe false
                    store.get(first).boostEnabled(default = false) shouldBe false
                    store.get(second).trailsEnabled(default = true) shouldBe true
                    store.get(second).boostEnabled(default = false) shouldBe true
                    store.setBoost(first, true)
                }

                withPreferences(folder) { reloaded ->
                    reloaded.get(first) shouldBe PlayerPreferences(enabled = false, boost = true)
                    reloaded.get(second) shouldBe PlayerPreferences(enabled = null, boost = true)
                }
            } finally {
                folder.toFile().deleteRecursively()
            }
        }

        "ignores malformed UUID entries instead of losing valid preferences" {
            val folder = Files.createTempDirectory("trails-players-")
            val uuid = UUID.fromString("33333333-3333-3333-3333-333333333333")
            try {
                Files.writeString(
                    folder.resolve("players.yml"),
                    """
                    players:
                      not-a-uuid:
                        enable: false
                      $uuid:
                        enable: true
                        boost: false
                    """.trimIndent(),
                )

                withPreferences(folder) { store ->
                    store.snapshot().keys shouldBe setOf(uuid)
                    store.get(uuid) shouldBe PlayerPreferences(enabled = true, boost = false)
                }
            } finally {
                folder.toFile().deleteRecursively()
            }
        }

        "migrates the legacy comment-only default file" {
            val folder = Files.createTempDirectory("trails-players-")
            val uuid = UUID.fromString("44444444-4444-4444-4444-444444444444")
            try {
                Files.writeString(folder.resolve("players.yml"), "## DO NOT EDIT THIS FILE\n")

                withPreferences(folder) { store -> store.setEnabled(uuid, false) }

                withPreferences(folder) { reloaded ->
                    reloaded.get(uuid).enabled shouldBe false
                }
            } finally {
                folder.toFile().deleteRecursively()
            }
        }

        "save admission coalesces markers and close remains pending through delayed IO" {
            val folder = Files.createTempDirectory("trails-players-delayed-")
            val entered = CountDownLatch(1)
            val release = CountDownLatch(1)
            val saves = AtomicInteger()
            val uuid = UUID.randomUUID()
            mockkConstructor(YamlConfig::class)
            every { anyConstructed<YamlConfig>().saveStrict() } answers {
                Thread.currentThread().name.startsWith("Trails-player-data") shouldBe true
                if (saves.incrementAndGet() == 1) {
                    entered.countDown()
                    check(release.await(5, TimeUnit.SECONDS))
                }
                callOriginal()
            }
            val store = PlayerPreferencesStore(folder)
            try {
                store.setEnabled(uuid, false)
                store.saveAsync()
                entered.await(5, TimeUnit.SECONDS) shouldBe true
                repeat(10_000) { store.setBoost(uuid, it % 2 == 0); store.saveAsync() }
                store.setEnabled(uuid, true)
                val close = store.closeAsync()
                close.isDone shouldBe false
                release.countDown()
                close.get(5, TimeUnit.SECONDS)
                (saves.get() <= 3) shouldBe true
                withPreferences(folder) { reloaded ->
                    reloaded.get(uuid) shouldBe PlayerPreferences(enabled = true, boost = false)
                }
            } finally {
                release.countDown()
                store.closeAsync().get(5, TimeUnit.SECONDS)
                unmockkConstructor(YamlConfig::class)
                folder.toFile().deleteRecursively()
            }
        }
    })

private fun <T> withPreferences(folder: Path, operation: (PlayerPreferencesStore) -> T): T {
    val store = PlayerPreferencesStore(folder)
    try { return operation(store) } finally { store.closeAsync().get(5, TimeUnit.SECONDS) }
}
